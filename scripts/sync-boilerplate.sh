#!/usr/bin/env bash
# Generates versions.tf, providers.tf, variables_common.tf and backend.tf in every stage root
# (1-org .. 5-workloads) from stages/_shared. Run it after editing _shared or adding a root.
# The state bucket is not written into backend.tf: pass it at init time with
#   terraform init -backend-config="bucket=<TF_STATE_BUCKET>"
# 0-bootstrap is excluded on purpose: it has its own files and a one-time local-to-GCS state migration.
set -euo pipefail
cd "$(dirname "$0")/.."

roots=(stages/1-org stages/2-security)
for stage in 3-networks 4-projects 5-workloads; do
  for env in dev qa prod; do
    roots+=("stages/${stage}/envs/${env}")
  done
done

for r in "${roots[@]}"; do
  mkdir -p "$r"
  cp stages/_shared/versions.tf "$r/versions.tf"
  cp stages/_shared/providers.tf "$r/providers.tf"
  cp stages/_shared/variables_common.tf "$r/variables_common.tf"

  prefix="${r#stages/}"           # 3-networks/envs/prod
  prefix="${prefix/\/envs\//\/}"  # 3-networks/prod
  cat > "$r/backend.tf" <<EOF
# Generated by scripts/sync-boilerplate.sh. Do not edit.
# terraform init -backend-config="bucket=<TF_STATE_BUCKET>"
terraform {
  backend "gcs" {
    prefix = "${prefix}"
  }
}
EOF
done

echo "Synced ${#roots[@]} roots."
